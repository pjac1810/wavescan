"""Generate src/tables.h for WAVESCAN (integers only on the FM-1).

FILT_G[i]   TPT one-pole G = g / (1 + g), g = tan(pi fc / fs), Q16; fc 20 Hz .. 16 kHz, exponential (i 0..1023)
ENV_MS[v]   an envelope or glide time for a 0..127 value: 1 ms .. 12 s, exponential
LFO_INC[v]  the LFO's phase step per frame for a 0..127 rate: 0.03 .. 40 Hz, exponential
"""
import math
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parents[1] / "src" / "tables.h"


def rows(vals, per):
  return "\n".join("  " + ", ".join(f"{v}u" for v in vals[i : i + per]) + "," for i in range(0, len(vals), per))


g = []
for i in range(1024):
  fc = 20.0 * (16000.0 / 20.0) ** (i / 1023)
  t = math.tan(math.pi * fc / FS)
  g.append(round(t / (1 + t) * 65536))
ms = [max(1, round(1.0 * (12000.0 / 1.0) ** (v / 127))) for v in range(128)]
lfo = [round(0.03 * (40 / 0.03) ** (v / 127) / FS * 2**32) for v in range(128)]
OUT.write_text(
  "/* SPDX-License-Identifier: GPL-3.0-only */\n/* generated by tools/gen_tables.py: do not edit */\n"
  "#ifndef WAVESCAN_TABLES_H\n#define WAVESCAN_TABLES_H\n#include <stdint.h>\n\n"
  f"static const uint16_t FILT_G[1024] = {{\n{rows(g, 16)}\n}};\n\n"
  f"static const uint16_t ENV_MS[128] = {{\n{rows(ms, 16)}\n}};\n\n"
  f"static const uint32_t LFO_INC[128] = {{\n{rows(lfo, 8)}\n}};\n\n#endif\n"
)
print("wrote", OUT)
